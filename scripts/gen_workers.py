#!/usr/bin/env python3
"""Generate docker-compose.workers.yml: one worker container per IP in config/ips.txt."""
import pathlib
import re

root = pathlib.Path(__file__).resolve().parent.parent
ips = [l.strip() for l in (root / "config" / "ips.txt").read_text().splitlines()
       if l.strip() and not l.strip().startswith("#")]
for ip in ips:
    if not re.fullmatch(r"\d{1,3}(\.\d{1,3}){3}", ip):
        raise SystemExit(f"Invalid IP in config/ips.txt: {ip}")
ips = list(dict.fromkeys(ips))  # a repeated IP must not create a second worker
if not ips:
    raise SystemExit("config/ips.txt has no IPs")

out = ["# GENERATED by scripts/gen_workers.py - do not edit", "services:"]
for ip in ips:
    out += [f"  worker_{ip.replace('.', '_')}:",
            "    image: emailval:latest",
            "    network_mode: host",
            "    restart: unless-stopped",
            "    env_file: .env",
            "    environment:",
            f'      SOURCE_IP: "{ip}"',
            "    command: python -m app.worker",
            "    depends_on:",
            "      db: { condition: service_healthy }"]
(root / "docker-compose.workers.yml").write_text("\n".join(out) + "\n")
print(f"Wrote docker-compose.workers.yml with {len(ips)} worker(s)")
